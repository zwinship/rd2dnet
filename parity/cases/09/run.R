nodes <- read.csv(file.path(d, 'nodes.csv'))
edges <- read.csv(file.path(d, 'edges.csv'), stringsAsFactors = FALSE)
obs <- read.csv(file.path(d, 'obs.csv'))
B <- as.matrix(read.csv(file.path(d, 'boundary.csv')))
net <- network_graph(edges, nodes, metric = transition_cost("length", class_attr = "cls", default_penalty = 50.4, connectors = "c"), directed = FALSE, direction = 'both')
bnd <- boundary(B, treated_side = 'left')
cc <- network_coordinates(net, bnd, as.matrix(obs[, c('x', 'y')]), n_eval = 7)
write.csv(data.frame(s = cc$s, treated = as.integer(cc$treated), arc = cc$crossing_arc), file.path(d, 'r_coords.csv'), row.names = FALSE)
res <- rdnet(obs$y_out, cc, kernel = 'uniform', p = 1, seed = 0, vce = 'hc1', h = 407.4, covs = as.matrix(obs[, 'z1', drop = FALSE]))
write_res(res$table, file.path(d, 'r_res_1.csv'))
write_agg(res, file.path(d, 'r_agg_1.csv'))
res <- rdnet(obs$y_out, cc, kernel = 'triangular', p = 1, seed = 0, vce = 'hc1', h = 265.4, covs = as.matrix(obs[, 'z1', drop = FALSE]))
write_res(res$table, file.path(d, 'r_res_2.csv'))
res <- rdnet(obs$y_out, cc, kernel = 'triangular', p = 1, seed = 0, vce = 'hc2', bwselect = 'cerrd', covs = as.matrix(obs[, 'z1', drop = FALSE]))
write_res(res$table, file.path(d, 'r_res_3.csv'))
dr <- density(cc, normalize = 'network', bwselect = 'common')
write.csv(data.frame(diff = dr$diff, diff_bc = dr$diff_bc, se = dr$se, h_left = dr$h_left, h_right = dr$h_right), file.path(d, 'r_dens_1.csv'), row.names = FALSE)
bw <- rdbwnet(obs$y_out, cc, bwselect = 'msetwo')
write.csv(data.frame(h0 = bw$h0, h1 = bw$h1, status = status_code(bw$status)), file.path(d, 'r_bw_1.csv'), row.names = FALSE)
run_bins(obs, cc, d, 350.0)
mt <- manipulation_test(cc, q = 60, reps = 500)
write.csv(data.frame(statistic = mt$statistic, pvalue = mt$pvalue, n_treated = mt$n_treated), file.path(d, 'r_manip_1.csv'), row.names = FALSE)
